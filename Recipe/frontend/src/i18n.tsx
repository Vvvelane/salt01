const LanguageContext = createContext<{ language: Language; toggleLanguage: () => void }>({ language: 'normal', toggleLanguage: () => {} });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    try { return localStorage.getItem('recipe.language') === 'en' ? 'en' : 'normal'; }
    catch { return 'normal'; }
  });
  useEffect(() => {
    document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
    try { localStorage.setItem('recipe.language', language); } catch { /* Storage may be unavailable. */ }
  }, [language]);
  return <LanguageContext.Provider value={{ language, toggleLanguage: () => setLanguage((current) => current === 'en' ? 'normal' : 'en') }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  const t = useCallback((text: string | null | undefined, english?: string): string => {
    if (!text) return '';
    if (context.language !== 'en') return text;
    return english ?? EN[text] ?? REGISTRY_EN[text] ?? text.match(/（([^（）]*[A-Za-z][^（）]*)）\s*$/)?.[1] ?? text;
  }, [context.language]);
  return { ...context, t };
}
